#!/usr/bin/env node
"use strict";

/**
 * Builds the distributable userscript from the local, reviewed sources.
 *
 * The generated clarIP.user.js contains the metadata block, the overlay markup,
 * styles and notification template, and the notif.js/script.js sources. Nothing
 * is fetched or evaluated at runtime by the loader.
 *
 * Usage: node scriptloader.js
 */

const fs = require("node:fs");
const path = require("node:path");

const root = __dirname;

const read = (file) => {
    const filePath = path.join(root, file);
    if (!fs.existsSync(filePath)) {
        throw new Error("Missing source file: " + file);
    }
    return fs.readFileSync(filePath, "utf8");
};

const metadata = `// ==UserScript==
// @name         clarIP
// @namespace    https://github.com/yuig/clarIP
// @version      0.66
// @description  ome.tv overlay with notifications
// @author       clara
// @match        https://ome.tv/*
// @match        https://www.ome.tv/*
// @run-at       document-idle
// @icon         https://www.google.com/s2/favicons?domain=ome.tv
// @updateURL    https://raw.githubusercontent.com/yuig/clarIP/main/clarIP.user.js
// @downloadURL  https://raw.githubusercontent.com/yuig/clarIP/main/clarIP.user.js
// @grant        none
// ==/UserScript==
`;

const assets = {
    markup: read("index.html"),
    style: read("style.css"),
    notificationTemplate: read("notification.html"),
};

const bundle = `${metadata}
/* Generated by scriptloader.js. Do not edit directly; edit the source files instead. */
(function () {
    "use strict";

    window.__clarIPAssets = ${JSON.stringify(assets, null, 4)};

${read("notif.js")}

${read("script.js")}
})();
`;

const outputPath = path.join(root, "clarIP.user.js");
fs.writeFileSync(outputPath, bundle, "utf8");
console.log("Built " + path.relative(process.cwd(), outputPath));
